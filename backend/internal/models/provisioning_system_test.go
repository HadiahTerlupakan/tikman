// TestAutoMigrateProvisioningTables verifies that the new provisioning tables
// are created by AutoMigrate with the expected columns.
func TestAutoMigrateProvisioningTables(t *testing.T) {
	db, err := gorm.Open(sqlite.Open(":memory:"), &gorm.Config{})
	if err != nil {
		t.Fatalf("open: %v", err)
	}

	if err := AutoMigrate(db); err != nil {
		t.Fatalf("AutoMigrate: %v", err)
	}

	for _, name := range []string{"config_templates", "provisioning_jobs", "batch_jobs"} {
		var exists bool
		if err := db.Raw(`SELECT EXISTS(SELECT 1 FROM sqlite_master WHERE type='table' AND name=?)`, name).Scan(&exists).Error; err != nil {
			t.Fatalf("check table %s: %v", name, err)
		}
		if !exists {
			t.Errorf("table %s was not created", name)
		}
	}
}

