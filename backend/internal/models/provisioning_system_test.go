// TestUniqueTemplateNameEnforced checks the unique name constraint is active.
func TestUniqueTemplateNameEnforced(t *testing.T) {
	db, err := gorm.Open(sqlite.Open(":memory:"), &gorm.Config{})
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	if err := AutoMigrate(db); err != nil {
		t.Fatalf("AutoMigrate: %v", err)
	}

	if err := db.Create(&ConfigTemplate{Name: "dup", Vendor: VendorZTE}).Error; err != nil {
		t.Fatalf("first insert: %v", err)
	}
	if err := db.Create(&ConfigTemplate{Name: "dup", Vendor: VendorHSGQ}).Error; err == nil {
		t.Error("duplicate template name should be rejected")
	}
}
